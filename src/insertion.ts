import { isBlankTaskLine, isPrefixOnlyDraft } from './capture';

/**
 * Pure text-editing functions. Every function that inserts text returns the
 * resulting selection (source offsets) so the editor can place the caret
 * without inferring anything.
 */

export interface Selection {
  start: number;
  end: number;
}

export interface LineBounds {
  start: number;
  end: number;
  text: string;
}

export function lineBoundsAt(content: string, index: number, includeNewline = false): LineBounds {
  const clamped = Math.max(0, Math.min(index, content.length));
  const start = content.lastIndexOf('\n', Math.max(0, clamped - 1)) + 1;
  let end = content.indexOf('\n', clamped);
  if (end === -1) end = content.length;
  return { start, end: includeNewline ? end : end, text: content.slice(start, end) };
}

export function lastLineBounds(content: string): LineBounds {
  return lineBoundsAt(content, content.length);
}

export interface InsertionResult {
  content: string;
  selection: Selection;
  /** Index where `text` was placed. */
  at: number;
}

/** Insert/replace at a selection, returning the caret position after the insert. */
export function applyInsert(content: string, selection: Selection, text: string): InsertionResult {
  const start = Math.max(0, Math.min(selection.start, content.length));
  const end = Math.max(start, Math.min(selection.end, content.length));
  const next = content.slice(0, start) + text + content.slice(end);
  return { content: next, selection: { start: start + text.length, end: start + text.length }, at: start };
}

export interface DraftLine {
  /** Absolute range of the generated draft line. */
  start: number;
  end: number;
  prefix: string;
}

export interface OpenInsertion {
  content: string;
  selection: Selection;
  /** Set when the resulting last line is exactly the generated draft. */
  draft: DraftLine | null;
  /** True when a brand-new line was appended. */
  appended: boolean;
}

/**
 * Decide what `open()` does to the document.
 *
 * - empty document           → draft at offset zero
 * - last line is bare `- [ ]`→ reuse the line with the captured prefix
 * - last line is the freshly generated prefix-only draft
 *                            → reuse it on the same screen, replace it only if
 *                              this session still owns it and the screen changed
 * - anything else            → append one newline and a fresh task
 *
 * An arbitrary user-authored line is never treated as disposable.
 */
export interface OpenInsertionOptions {
  /** True when the capture label matches the current session's draft label. */
  sameScreen: boolean;
  /** True when the last line is this session's own generated draft. */
  ownsDraft: boolean;
  /** The draft prefix generated by this session (used to recognise its line). */
  previousPrefix?: string | null;
}

export function planOpenInsertion(content: string, prefix: string, options: OpenInsertionOptions): OpenInsertion {
  const previousPrefix = options.previousPrefix ?? null;
  const knownPrefixes = [prefix, previousPrefix].filter((value): value is string => Boolean(value));

  if (content === '') {
    return {
      content: prefix,
      selection: { start: prefix.length, end: prefix.length },
      draft: { start: 0, end: prefix.length, prefix },
      appended: false,
    };
  }

  const last = lastLineBounds(content);

  if (isBlankTaskLine(last.text)) {
    const next = content.slice(0, last.start) + prefix;
    return {
      content: next,
      selection: { start: next.length, end: next.length },
      draft: { start: last.start, end: next.length, prefix },
      appended: false,
    };
  }

  const isOwnDraft = knownPrefixes.some((known) => isPrefixOnlyDraft(last.text, known));
  if (isOwnDraft && (options.sameScreen || options.ownsDraft)) {
    const draftPrefix = knownPrefixes.find((known) => isPrefixOnlyDraft(last.text, known)) as string;
    if (draftPrefix === prefix) {
      const caret = last.start + prefix.length;
      return {
        content,
        selection: { start: caret, end: caret },
        draft: { start: last.start, end: last.start + prefix.length, prefix },
        appended: false,
      };
    }
    // Same untouched draft line, different screen: relabel in place.
    const next = content.slice(0, last.start) + prefix;
    return {
      content: next,
      selection: { start: next.length, end: next.length },
      draft: { start: last.start, end: next.length, prefix },
      appended: false,
    };
  }

  const next = content + '\n' + prefix;
  return {
    content: next,
    selection: { start: next.length, end: next.length },
    draft: { start: content.length + 1, end: next.length, prefix },
    appended: true,
  };
}

/**
 * Remove the generated draft line on close, but only when it is provably
 * untouched (nothing typed after the prefix). Never removes edited text.
 */
export function planCloseRemoval(content: string, draft: DraftLine | null): { content: string; removed: boolean } {
  if (!draft) return { content, removed: false };
  const line = lineBoundsAt(content, draft.start);
  const lineText = content.slice(line.start, line.end);
  if (lineText.replace(/\s+$/u, '') !== draft.prefix.replace(/\s+$/u, '')) return { content, removed: false };
  if (line.start === 0) {
    const rest = content[line.end] === '\n' ? content.slice(line.end + 1) : '';
    return { content: rest, removed: true };
  }
  return { content: content.slice(0, line.start - 1) + content.slice(line.end), removed: true };
}
